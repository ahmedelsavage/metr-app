strategy = sys.argv[1] if len(sys.argv) > 1 else None
rag = RAG()
hits = {1: 0, 3: 0, 5: 0}

for clause, expected in CASES:
    res = rag.search(clause, limit=5, strategy=strategy)
    arts = [r.article_number for r in res]
    rank = next((i + 1 for i, a in enumerate(arts) if a in expected), None)
    for k in hits:
        if rank and rank <= k:
            hits[k] += 1
    mark = "OK" if rank == 1 else ("~~" if rank else "XX")
    print(f"[{mark}] متوقع {expected} | طلع {arts} | أعلى score {res[0].score:.3f}")
    print("     ", clause[:75])

